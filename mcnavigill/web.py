"""Export the graph and every entrance-to-entrance route for the browser front end.

The web app in ``web/`` does no routing of its own. It reads ``web/data.js``, written here
from the same graph and the same Pareto search the Python package uses, so there is one
routing implementation and the page can be served as static files.

For each ordered pair of entrances the export holds the Pareto front, shortest first. Its
first route is the ``shortest`` optimum and its last is the ``warmest`` one; the tests check
both against ``dijkstra``.
"""

from __future__ import annotations

import itertools
import json
from collections import Counter
from pathlib import Path

from .graph import CampusGraph
from .routing import WALKING_SPEED_M_PER_MIN, pareto_routes


def _r(v: float) -> float:
    return round(v, 1)


def entrance_labels(graph: CampusGraph) -> dict[str, str]:
    per_building = Counter(n.building for n in graph.entrances())
    return {n.id: (f"{n.building} (entrance {n.id})" if per_building[n.building] > 1
                   else n.building)
            for n in graph.entrances()}


def build_data(graph: CampusGraph | None = None) -> dict:
    g = graph or CampusGraph.load()
    labels = entrance_labels(g)
    entrances = sorted(g.entrances(), key=lambda n: (n.building, int(n.id)))
    routes = {}
    for a, b in itertools.permutations([n.id for n in entrances], 2):
        routes[f"{a}|{b}"] = [
            {"n": list(r.nodes), "L": _r(r.length_m), "O": _r(r.outdoor_m)}
            for r in pareto_routes(g, a, b)
        ]
    return {
        "speed": WALKING_SPEED_M_PER_MIN,
        "nodes": {n.id: {"x": _r(n.x), "y": _r(n.y), "kind": n.kind, "b": n.building}
                  for n in g.nodes.values()},
        "edges": [{"u": e.u, "v": e.v, "k": e.kind, "L": _r(e.length_cm / 100),
                   "p": [[_r(x), _r(y)] for x, y in e.points]} for e in g.edges],
        "entrances": [{"id": n.id, "label": labels[n.id]} for n in entrances],
        "routes": routes,
    }


def render_data_js(data: dict) -> str:
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    return ("// Generated by scripts/build_web.py from mcnavigill/data. Do not edit by hand.\n"
            f"window.MCNAV = {body};\n")


def write_data_js(path: str | Path = "web/data.js") -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_data_js(build_data()), encoding="utf-8")
    return path
